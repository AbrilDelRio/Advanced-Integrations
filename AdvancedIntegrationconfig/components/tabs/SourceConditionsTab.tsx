import * as React from "react";
import { PrimaryButton, DefaultButton, TextField, Icon } from "@fluentui/react";
import { SourceConditionRow } from "../../types";
import { EntityPicker } from "../pickers/EntityPicker";
import { FieldPicker } from "../pickers/FieldPicker";
import { MetaChoicePicker } from "../pickers/MetaChoicePicker";
import { useMetaOptions, labelFor, labelImpliesNoValue } from "../shared/useMetaOptions";
import { Page, PageHeader, FieldGrid, Field, EmptyState } from "../shared/Layout";
const ENTITY = "mfd_advancedintegrationcondition";
type WorkingRow = SourceConditionRow & {
    _key: string;
};
const newTempKey = () => "new-" + Math.random().toString(36).slice(2, 10) + Date.now().toString(36);
const withKey = (r: SourceConditionRow): WorkingRow => ({ ...r, _key: r.mfd_advancedintegrationconditionid ?? r._tempKey ?? "" });
const strip = (r: WorkingRow): SourceConditionRow => { const { _key, ...rest } = r; return rest; };
export const SourceConditionsTab: React.FC<{
    rows: SourceConditionRow[];
    sourceEntity?: string | null;
    onChange: (rows: SourceConditionRow[]) => void;
}> = ({ rows, sourceEntity, onChange }) => {
    const working = React.useMemo(() => rows.map(withKey), [rows]);
    const [selectedKey, setSelectedKey] = React.useState<string | null>(working[0]?._key ?? null);
    const selected = working.find(r => r._key === selectedKey) ?? null;
    const commit = (next: WorkingRow[]) => onChange(next.map(strip));
    React.useEffect(() => {
        if (!sourceEntity)
            return;
        if (rows.some(r => r.mfd_entity !== sourceEntity)) {
            onChange(rows.map(r => ({ ...r, mfd_entity: sourceEntity })));
        }
    }, [sourceEntity]);
    const operatorOptions = useMetaOptions(ENTITY, "mfd_condition");
    const opLabel = labelFor(operatorOptions, selected?.mfd_condition);
    const noValue = labelImpliesNoValue(opLabel);
    const addRow = () => {
        const tempKey = newTempKey();
        const nr = withKey({ mfd_entity: sourceEntity ?? null, _tempKey: tempKey });
        commit([...working, nr]);
        setSelectedKey(tempKey);
    };
    const updateSelected = (patch: Partial<SourceConditionRow>) => {
        commit(working.map(r => (r._key === selectedKey ? { ...r, ...patch } : r)));
    };
    const removeSelected = () => {
        if (!selectedKey)
            return;
        commit(working.filter(r => r._key !== selectedKey));
        setSelectedKey(null);
    };
    return (<Page wide>
      <PageHeader title="Source Conditions" subtitle="Gate the integration on values in the source record" actions={<PrimaryButton text="Add condition" iconProps={{ iconName: "Add" }} onClick={addRow}/>}/>

      <div className="pccfg-split">
        <div className="pccfg-list">
          <div className="pccfg-list-head"><Icon iconName="FilterSettings"/> Source conditions</div>
          <div className="pccfg-list-scroll">
            {working.map(r => (<div key={r._key} onClick={() => setSelectedKey(r._key)} className={r._key === selectedKey ? "pccfg-row is-selected" : "pccfg-row"}>
                <div className="pccfg-row-main">
                  <div className="pccfg-row-title">{r.mfd_code || "(new condition)"}</div>
                  <div className="pccfg-row-sub">{r.mfd_field ?? "?"}</div>
                </div>
              </div>))}
            {working.length === 0 && <EmptyState icon="FilterSettings" title="No conditions yet" detail="Add one to start."/>}
          </div>
        </div>

        <div className="pccfg-detail">
          {selected ? (<FieldGrid single>
              {selected.mfd_code && (<Field><TextField label="Code" value={selected.mfd_code} disabled description="Auto-generated by Dataverse"/></Field>)}
              <Field><EntityPicker label="Source entity" required disabled value={sourceEntity} onChange={() => undefined}/></Field>
              <Field><FieldPicker label="Field" required entity={sourceEntity} value={selected.mfd_field} onChange={(v) => updateSelected({ mfd_field: v ?? null })}/></Field>
              <Field><MetaChoicePicker label="Operator" required entity={ENTITY} attribute="mfd_condition" value={selected.mfd_condition} onChange={(v) => updateSelected({ mfd_condition: v })}/></Field>
              {!noValue && (<Field><TextField label="Value" value={selected.mfd_value ?? ""} onChange={(_, v) => updateSelected({ mfd_value: v ?? "" })}/></Field>)}
              <Field span>
                <DefaultButton text="Remove" iconProps={{ iconName: "Delete" }} onClick={removeSelected}/>
              </Field>
            </FieldGrid>) : (<EmptyState icon="FilterSettings" title="Nothing selected" detail="Select a condition on the left, or add a new one."/>)}
        </div>
      </div>
    </Page>);
};
