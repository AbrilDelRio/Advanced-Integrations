import * as React from "react";
import { TextField, Dropdown, IDropdownOption, ActionButton } from "@fluentui/react";
import { AdvancedMapping } from "../../types";
import { EntityPicker } from "../pickers/EntityPicker";
import { MetaChoicePicker, MetaMultiChoicePicker } from "../pickers/MetaChoicePicker";
import { RecordLookupPicker } from "../pickers/RecordLookupPicker";
import { getTeams, TeamMeta } from "../../services/metadataService";
import { Page, PageHeader, Card, FieldGrid, Field, SwitchRow, SwitchList } from "../shared/Layout";
const HEADER_ENTITY = "mfd_advancedmapping";
export const GeneralSettingsTab: React.FC<{
    header: AdvancedMapping;
    onChange: (patch: Partial<AdvancedMapping>) => void;
}> = ({ header, onChange }) => {
    const [teams, setTeams] = React.useState<TeamMeta[]>([]);
    React.useEffect(() => { getTeams().then(setTeams).catch(() => setTeams([])); }, []);
    const teamOptions: IDropdownOption[] = teams.map(t => ({ key: t.id, text: t.name }));
    return (<Page>
      <PageHeader title="General" subtitle="Core configuration for this integration"/>

      <Card icon="Info" title="Identity" subtitle="Name and description for this integration">
        <FieldGrid>
          <Field><TextField label="Code" value={header.mfd_eventfortable ?? "(auto-generated on save)"} disabled description="Auto-generated by Dataverse"/></Field>
          <Field><TextField label="Application ID" autoComplete="off" value={header.mfd_applicationid ?? ""} onChange={(_, v) => onChange({ mfd_applicationid: v ?? "" })}/></Field>
          <Field span><TextField label="Description" multiline rows={3} value={header.mfd_description ?? ""} onChange={(_, v) => onChange({ mfd_description: v ?? "" })}/></Field>
        </FieldGrid>
      </Card>

      <Card icon="Upload" title="Source event" subtitle="What triggers this integration">
        <FieldGrid>
          <Field><EntityPicker label="Source entity" required value={header.mfd_eventforsourceentity} onChange={(v) => onChange({ mfd_eventforsourceentity: v })}/></Field>
          <Field><MetaChoicePicker label="Event type" entity={HEADER_ENTITY} attribute="mfd_eventtype" value={header.mfd_eventtype} onChange={(v) => onChange({ mfd_eventtype: v })}/></Field>
        </FieldGrid>
      </Card>

      <Card icon="Download" title="Destination event" subtitle="Where the integration writes to">
        <FieldGrid>
          <Field><EntityPicker label="Destination entity" required value={header.mfd_destinationentity} onChange={(v) => onChange({ mfd_destinationentity: v })}/></Field>
          <Field><MetaChoicePicker label="Destination event type" entity={HEADER_ENTITY} attribute="mfd_destinationeventtype" value={header.mfd_destinationeventtype} onChange={(v) => onChange({ mfd_destinationeventtype: v })}/></Field>
        </FieldGrid>
      </Card>

      <Card icon="Settings" title="Behavior">
        <SwitchList>
          <SwitchRow title="Enabled" description="Turn this integration on or off" checked={!!header.mfd_enabled} onChange={(c) => onChange({ mfd_enabled: c })}/>
          <SwitchRow title="Log usage" description="Keep a run log for this integration" checked={!!header.mfd_logusage} onChange={(c) => onChange({ mfd_logusage: c })}/>
        </SwitchList>
      </Card>

      <Card icon="Contact" title="Run under user" subtitle="User or service account the integration runs as. Empty = Calling User">
        <FieldGrid>
          <Field><RecordLookupPicker label="Run under user" entity="systemuser" value={header.mfd_rununderuser ?? null} onChange={(id) => onChange({ mfd_rununderuser: id })}/></Field>
          {header.mfd_rununderuser && (<Field><ActionButton iconProps={{ iconName: "Clear" }} text="Clear (use Calling User)" onClick={() => onChange({ mfd_rununderuser: null })}/></Field>)}
        </FieldGrid>
      </Card>

      <Card icon="MailAlert" title="Error notifications">
        <SwitchList>
          <SwitchRow title="Send notification on error" description="Alert a team when this integration fails" checked={!!header.mfd_sendnotificaitononerror} onChange={(c) => onChange({ mfd_sendnotificaitononerror: c })}/>
        </SwitchList>
        {header.mfd_sendnotificaitononerror && (<FieldGrid>
            <Field><Dropdown label="Notification team" placeholder="Select a team..." options={teamOptions} selectedKey={header.mfd_errornotificationteam ?? undefined} onChange={(_, o) => onChange({ mfd_errornotificationteam: o ? String(o.key) : null })}/></Field>
            <Field><MetaMultiChoicePicker label="Notify team via" entity={HEADER_ENTITY} attribute="mfd_notificationteamonerrorvia" value={header.mfd_notificationteamonerrorvia} onChange={(v) => onChange({ mfd_notificationteamonerrorvia: v })}/></Field>
          </FieldGrid>)}
      </Card>

      <Card icon="Ringer" title="User notifications">
        <SwitchList>
          <SwitchRow title="Notify user" description="Alert the record owner or related user" checked={!!header.mfd_notifyuser} onChange={(c) => onChange({ mfd_notifyuser: c })}/>
        </SwitchList>
        {header.mfd_notifyuser && (<FieldGrid single>
            <Field><MetaMultiChoicePicker label="Notify user via" entity={HEADER_ENTITY} attribute="mfd_usernotificationmehtod" value={header.mfd_usernotificationmehtod} onChange={(v) => onChange({ mfd_usernotificationmehtod: v })}/></Field>
          </FieldGrid>)}
      </Card>
    </Page>);
};
